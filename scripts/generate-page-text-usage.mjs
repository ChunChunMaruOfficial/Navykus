// Lists the locale keys that match a page of «Дерево текстов» (src/page-texts.ts) but are not
// used anywhere by the site code. Most of them are leftovers of the old hard-coded content
// (championship description, jury names, FAQ answers…) that now lives in the CMS collections —
// they must not be editable in the tree. Output: src/page-text-unused.generated.ts
//
// Run after adding / removing site texts: npm run gen:pagetext-usage
import fs from 'node:fs';
import path from 'node:path';
import { EDITABLE_PAGE_TEXT_PAGES, flattenLocaleText, pageTextKeyMatchers } from '../src/page-texts.ts';

const ROOT = process.cwd();
const OUTPUT = path.join(ROOT, 'src', 'page-text-unused.generated.ts');
const SCAN_DIRS = ['src', 'server'];
const SKIP = [
  /[\\/]admin[\\/]/,
  /[\\/]i18n[\\/]locales[\\/]/,
  /[\\/]migrations[\\/]/,
  /[\\/]page-texts\.ts$/,
  /[\\/]page-text-unused\.generated\.ts$/,
  /[\\/]payload-types\.ts$/,
  /[\\/]payload-generated-schema\.ts$/,
];
// Keys the code builds at runtime (template literals / returnObjects).
const DYNAMIC_PREFIXES = [
  'ui.app.pillar',
  'ui.app.trust',
  'ui.activitiespage.scenario',
  'languages.',
  'privacypolicy.',
];

const walk = (dir) => fs.readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
  const full = path.join(dir, entry.name);
  if (entry.isDirectory()) return entry.name === 'node_modules' ? [] : walk(full);
  return /\.(tsx?|mjs|js)$/.test(entry.name) && !SKIP.some((re) => re.test(full)) ? [full] : [];
});

const source = SCAN_DIRS.flatMap((dir) => walk(path.join(ROOT, dir)))
  .map((file) => fs.readFileSync(file, 'utf8'))
  .join('\n');
const usedLiterals = new Set(source.match(/(?<=['"`])[A-Za-z][\w-]*(?:\.[\w-]+)+(?=['"`])/g) ?? []);

const flatLocale = flattenLocaleText(
  JSON.parse(fs.readFileSync(path.join(ROOT, 'src', 'i18n', 'locales', 'ru', 'translation.json'), 'utf8')),
  '',
  { includeArrays: true },
);

// Same page matching as getEditablePageTextKeys, without the usage filter.
const candidates = new Set();
for (const { value: page } of EDITABLE_PAGE_TEXT_PAGES) {
  for (const key of Object.keys(flatLocale)) {
    if (pageTextKeyMatchers[page].some((matches) => matches(key))) candidates.add(key);
  }
}

const unused = [...candidates]
  .filter((key) => !usedLiterals.has(key) && !DYNAMIC_PREFIXES.some((prefix) => key.startsWith(prefix)))
  .sort();

const body = unused.map((key) => `  ${JSON.stringify(key)},`).join('\n');
fs.writeFileSync(
  OUTPUT,
  `// Generated by scripts/generate-page-text-usage.mjs — do not edit by hand.\n` +
    `// Locale keys that are not used by the site: hidden from «Дерево текстов».\n` +
    `export const UNUSED_PAGE_TEXT_KEYS: ReadonlySet<string> = new Set([\n${body}\n]);\n`,
  'utf8',
);
console.log(`${candidates.size} page-text keys, ${unused.length} unused -> ${path.relative(ROOT, OUTPUT)}`);
